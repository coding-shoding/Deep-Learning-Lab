# Perceptron Implementation (Class Definition)
section("TASK 4: PERCEPTRON IMPLEMENTATION (FROM SCRATCH)")


class SingleLayerPerceptron:
    """
    A Single Layer Perceptron implemented from first principles using the
    classical Rosenblatt perceptron learning rule.

        z      = w^T x + b                 (weighted sum)
        y_hat  = step(z)                   (step activation)
        w_new  = w_old + eta * (y - y_hat) * x
        b_new  = b_old + eta * (y - y_hat)
    """

    def __init__(self, n_features, learning_rate=0.01, n_epochs=50, random_state=42):
        rng = np.random.default_rng(random_state)
        # Small random weight initialization
        self.weights = rng.normal(loc=0.0, scale=0.01, size=n_features)
        self.bias = 0.0
        self.lr = learning_rate
        self.n_epochs = n_epochs
        # History logs for Task 5 / mandatory plots
        self.history = {
            "epoch": [], "errors": [], "weights": [], "bias": [], "train_error_rate": []
        }

    @staticmethod
    def step_activation(z):
        """Step Activation Function: f(z) = 1 if z >= 0 else 0."""
        return np.where(z >= 0, 1, 0)

    def forward(self, X):
        """Forward propagation: weighted sum -> step activation."""
        z = np.dot(X, self.weights) + self.bias
        return self.step_activation(z)

    def fit(self, X, y, verbose=True):
        """Train using the perceptron learning rule, logging progress per epoch."""
        n_samples = X.shape[0]
        for epoch in range(1, self.n_epochs + 1):
            misclassified = 0
            for xi, target in zip(X, y):
                z = np.dot(xi, self.weights) + self.bias
                y_hat = self.step_activation(z)
                error = target - y_hat
                if error != 0:
                    misclassified += 1
                    self.weights += self.lr * error * xi
                    self.bias += self.lr * error

            error_rate = misclassified / n_samples
            self.history["epoch"].append(epoch)
            self.history["errors"].append(misclassified)
            self.history["weights"].append(self.weights.copy())
            self.history["bias"].append(self.bias)
            self.history["train_error_rate"].append(error_rate)

            if verbose:
                print(f"Epoch {epoch:3d} | Misclassified: {misclassified:4d} "
                      f"| Bias: {self.bias: .4f} | "
                      f"Weights: {np.round(self.weights, 4)}")

            # Early stopping once perfectly classified (converged)
            if misclassified == 0:
                if verbose:
                    print(f"Converged at epoch {epoch} (0 misclassifications).")
                break
        return self

    def predict(self, X):
        return self.forward(X)

