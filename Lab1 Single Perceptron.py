# ADDITIONAL TASK 1: STEP vs SIGMOID ACTIVATION - DISCUSSION
# ==============================================================================
section("ADDITIONAL TASK 1: STEP vs SIGMOID ACTIVATION FUNCTION")

discussion_step_vs_sigmoid = """
Step Activation:
  f(z) = 1 if z >= 0 else 0
  - Output is discrete (0 or 1), with a discontinuous jump at z = 0.
  - Derivative is 0 everywhere except undefined at z = 0, so gradient
    descent / backpropagation cannot use it to compute meaningful
    weight updates in deeper, multi-layer networks.
  - Only usable with the simple perceptron learning rule shown above,
    which relies directly on the (target - prediction) error, not on
    calculus-based gradients.

Sigmoid Activation:
  f(z) = 1 / (1 + e^-z)
  - Output is continuous in (0, 1) and smoothly differentiable
    everywhere, giving a well-defined, non-zero gradient almost
    everywhere.
  - This differentiability is essential for backpropagation, which
    needs to propagate gradients of the loss function through every
    layer using the chain rule.
  - Continuous outputs can also be interpreted as class probabilities,
    which is useful for probabilistic decision-making and computing
    smooth loss functions such as binary cross-entropy.

Why modern deep learning avoids the Step function:
  1. Non-differentiability makes gradient-based optimization (SGD, Adam,
     etc.) impossible to apply directly.
  2. Zero gradient almost everywhere means no learning signal can flow
     backward through a stack of layers ("no gradient to propagate").
  3. Networks with step activations cannot represent smooth, complex
     decision surfaces the way sigmoid/tanh/ReLU-based deep networks can.
  Because of this, the Step function is retained only for pedagogical
  study of the classical Rosenblatt perceptron, while Sigmoid, Tanh,
  ReLU, Leaky ReLU, and Softmax are used in practice.
"""
print(discussion_step_vs_sigmoid)
with open(f"{RESULTS_DIR}/additional_task1_step_vs_sigmoid.txt", "w") as f:
    f.write(discussion_step_vs_sigmoid)


