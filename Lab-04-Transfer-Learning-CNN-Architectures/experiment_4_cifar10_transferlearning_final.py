"""## 5. Task 2 — Transfer Learning (VGG16)
Steps per the manual:
1. Load pretrained ImageNet weights.
2. Remove the original classification layer.
3. Freeze the convolutional base.
4. Add a Global Average Pooling layer.
5. Add a Dense layer with ReLU activation.
6. Add the output layer with Softmax activation.

Pretrained ImageNet models expect larger inputs than 32×32, so CIFAR-10 images are resized
(here to 96×96) using a `Resizing` layer inside the model graph.
"""

IMG_SIZE = 96  # resized input for pretrained backbones

def build_transfer_model(base_model_fn, img_size=IMG_SIZE, num_classes=10,
                          dense_units=256, name="TransferModel"):
    """Builds a transfer-learning model: resize -> pretrained base -> GAP -> Dense -> Softmax."""
    inputs = layers.Input(shape=(32, 32, 3))
    x = layers.Resizing(img_size, img_size)(inputs)

    base_model = base_model_fn(weights='imagenet', include_top=False,
                                input_shape=(img_size, img_size, 3))
    base_model.trainable = False  # freeze convolutional base

    x = base_model(x, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dense(dense_units, activation='relu')(x)
    x = layers.Dropout(0.3)(x)
    outputs = layers.Dense(num_classes, activation='softmax')(x)

    model = models.Model(inputs, outputs, name=name)
    return model, base_model

from tensorflow.keras.applications import VGG16

