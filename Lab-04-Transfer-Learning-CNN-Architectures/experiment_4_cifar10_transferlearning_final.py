"""## 12. Hyperparameter Study — Full Grid Required by the Manual

The manual specifies:

- Learning rate: `0.001`, `0.0001`
- Batch size: `16`, `32`, `64`
- Epochs: `10`, `20`
- Optimizer: `Adam`, `SGD`
- Dense units: `128`, `256`
- Frozen layers: `All`, `Partial`

The code below evaluates the **complete factorial grid (48 configurations)** rather than a representative subset. For the submitted experiment, leave `HP_EPOCHS_OVERRIDE = None` so each configuration uses its required 10 or 20 epochs.

"""

from itertools import product
import random

HP_EPOCHS_OVERRIDE = None  # None = exact manual study (10 or 20 epochs)
HP_LEARNING_RATES = [0.001, 0.0001]
HP_BATCH_SIZES = [16, 32, 64]
HP_EPOCHS = [10, 20]
HP_OPTIMIZERS = ['Adam', 'SGD']
HP_DENSE_UNITS = [128, 256]
HP_FROZEN = ['All', 'Partial']

def train_config(learning_rate, batch_size, epochs, optimizer_name, dense_units, frozen='All'):
    model, base = build_transfer_model(
        VGG16, dense_units=dense_units,
        name=f"VGG16_{optimizer_name}_{learning_rate}_{batch_size}_{epochs}_{dense_units}_{frozen}"
    )

    if frozen == 'Partial':
        base.trainable = True
        for layer in base.layers:
            layer.trainable = layer.name.startswith('block5')
    else:
        base.trainable = False

    if optimizer_name == 'Adam':
        opt = optimizers.Adam(learning_rate=learning_rate)
    else:
        opt = optimizers.SGD(learning_rate=learning_rate, momentum=0.9)

    model.compile(optimizer=opt, loss='categorical_crossentropy', metrics=['accuracy'])

    start = time.time()
    hist = model.fit(
        x_train, y_train_cat,
        validation_data=(x_val, y_val_cat),
        epochs=epochs if HP_EPOCHS_OVERRIDE is None else HP_EPOCHS_OVERRIDE,
        batch_size=batch_size, verbose=0
    )
    elapsed = time.time() - start
    test_loss, test_acc = model.evaluate(x_test, y_test_cat, verbose=0)

    return {
        'learning_rate': learning_rate,
        'batch_size': batch_size,
        'epochs': epochs,
        'optimizer': optimizer_name,
        'dense_units': dense_units,
        'frozen_layers': frozen,
        'training_accuracy': hist.history['accuracy'][-1],
        'validation_accuracy': hist.history['val_accuracy'][-1],
        'test_accuracy': test_acc,
        'training_time_s': elapsed,
        'parameters': model.count_params(),
        'actual_epochs': len(hist.history['accuracy'])
    }

all_configs = [
    dict(learning_rate=lr, batch_size=bs, epochs=ep, optimizer_name=opt,
         dense_units=du, frozen=fr)
    for lr, bs, ep, opt, du, fr in product(
        HP_LEARNING_RATES, HP_BATCH_SIZES, HP_EPOCHS,
        HP_OPTIMIZERS, HP_DENSE_UNITS, HP_FROZEN
    )
]

