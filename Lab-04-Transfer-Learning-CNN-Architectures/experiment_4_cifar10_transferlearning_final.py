"""## 4. AlexNet (Built From Scratch, Adapted for CIFAR-10)
The original AlexNet expects 227×227 inputs; here it is adapted (smaller strides/kernels,
no local response normalization) to work with 32×32 CIFAR-10 images while retaining its
key innovations: **ReLU activation, Dropout, and a deep stack of conv layers**.
"""

def build_alexnet(input_shape=(32, 32, 3), num_classes=10):
    model = models.Sequential(name="AlexNet_CIFAR")
    model.add(layers.Input(shape=input_shape))
    model.add(layers.Conv2D(64, (3, 3), strides=1, padding='same', activation='relu'))
    model.add(layers.MaxPooling2D((2, 2)))
    model.add(layers.Conv2D(192, (3, 3), padding='same', activation='relu'))
    model.add(layers.MaxPooling2D((2, 2)))
    model.add(layers.Conv2D(384, (3, 3), padding='same', activation='relu'))
    model.add(layers.Conv2D(256, (3, 3), padding='same', activation='relu'))
    model.add(layers.Conv2D(256, (3, 3), padding='same', activation='relu'))
    model.add(layers.MaxPooling2D((2, 2)))
    model.add(layers.Flatten())
    model.add(layers.Dense(1024, activation='relu'))
    model.add(layers.Dropout(0.5))
    model.add(layers.Dense(1024, activation='relu'))
    model.add(layers.Dropout(0.5))
    model.add(layers.Dense(num_classes, activation='softmax'))
    return model

