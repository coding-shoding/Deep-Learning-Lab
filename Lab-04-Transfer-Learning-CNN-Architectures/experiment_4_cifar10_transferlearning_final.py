"""## 10. Additional Exercise — GoogleNet / Inception Family Transfer Learning

The original GoogleNet (Inception-v1) is not provided as a standard TensorFlow/Keras application model. This notebook therefore uses **InceptionV3**, a later member of the Inception family, and labels it explicitly as an InceptionV3 substitute rather than claiming it is the original GoogleNet architecture.

"""

from tensorflow.keras.applications import InceptionV3

IMG_SIZE_INCEPTION = 139

def build_inception_model(dense_units=256, num_classes=10):
    inputs = layers.Input(shape=(32, 32, 3))
    x = layers.Resizing(IMG_SIZE_INCEPTION, IMG_SIZE_INCEPTION)(inputs)
    base = InceptionV3(weights='imagenet', include_top=False,
                        input_shape=(IMG_SIZE_INCEPTION, IMG_SIZE_INCEPTION, 3))
    base.trainable = False
