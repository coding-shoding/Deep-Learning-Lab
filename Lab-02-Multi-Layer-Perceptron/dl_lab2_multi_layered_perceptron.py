# Helper function to plot the decision boundary for an MLP
def plot_mlp_decision_boundary(X, y, model, title="MLP Decision Boundary", filename=None):
    plt.figure(figsize=(6, 5))

    # Plot data points
    plt.scatter(X[y == 0][:, 0], X[y == 0][:, 1], color='red', marker='o', label='Class 0 (Output 0)')
    plt.scatter(X[y == 1][:, 0], X[y == 1][:, 1], color='blue', marker='x', label='Class 1 (Output 1)')

    # Create a meshgrid to plot the decision boundary
    x_min, x_max = X[:, 0].min() - 0.5, X[:, 0].max() + 0.5
    y_min, y_max = X[:, 1].min() - 0.5, X[:, 1].max() + 0.5
    xx, yy = np.meshgrid(np.linspace(x_min, x_max, 100), np.linspace(y_min, y_max, 100))

    # Predict the class for each point on the meshgrid
    Z = model.predict(np.c_[xx.ravel(), yy.ravel()], verbose=0)
    Z = (Z > 0.5).astype(int) # Threshold at 0.5 for binary classification
    Z = Z.reshape(xx.shape)

    # Plot the decision boundary as a contour plot
    plt.contourf(xx, yy, Z, alpha=0.3, cmap=plt.cm.coolwarm)

    plt.xlabel('Input 1')
    plt.ylabel('Input 2')
    plt.title(title)
    plt.xlim(x_min, x_max)
    plt.ylim(y_min, y_max)
    plt.grid(True)
    plt.legend()

    if filename:
        plt.savefig(filename)
        plt.close() # Close the figure to avoid displaying it if not explicitly requested
    else:
        plt.show()

# Compile the model
