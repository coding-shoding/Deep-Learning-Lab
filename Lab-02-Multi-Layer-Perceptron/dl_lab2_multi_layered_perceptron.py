# Create a Sequential model
mlp_model = Sequential([
    # Input layer and first hidden layer
    # Increased hidden neurons to 4 for better convergence on XOR problem
    Dense(units=4, activation='tanh', input_shape=(2,)),
    # Output layer
    # Use 'sigmoid' activation for binary classification (0 or 1 output)
    # The output will be a probability, which we can threshold at 0.5
    Dense(units=1, activation='sigmoid')
])

