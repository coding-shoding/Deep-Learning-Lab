from scikeras.wrappers import KerasClassifier
from sklearn.model_selection import RandomizedSearchCV
from tensorflow.keras import optimizers, activations
from tensorflow.keras.layers import Dropout

# Function to create the Keras model, which will be used by SciKeras
def create_model(hidden_layers=1, hidden_neurons=128, learning_rate=0.001,
                 optimizer='adam', activation='relu', dropout_rate=0.0):
    model = models.Sequential()
    model.add(layers.Input(shape=(784,)))

    # Add hidden layers
    for _ in range(hidden_layers):
        model.add(layers.Dense(hidden_neurons, activation=activation))
        if dropout_rate > 0:
            model.add(Dropout(dropout_rate))

    model.add(layers.Dense(10, activation='softmax'))

    # Select optimizer
    # Ensure optimizer names match the string keys used in param_grid (now lowercase)
    if optimizer == 'adam':
        opt = optimizers.Adam(learning_rate=learning_rate)
    elif optimizer == 'sgd':
        opt = optimizers.SGD(learning_rate=learning_rate)
    elif optimizer == 'rmsprop':
        opt = optimizers.RMSprop(learning_rate=learning_rate)
    else:
        # Added a more descriptive error message in case of mismatch
        raise ValueError(f"Unknown optimizer: {optimizer}. Please use 'adam', 'sgd', or 'rmsprop' (lowercase).")

    model.compile(
        optimizer=opt,
        loss='categorical_crossentropy',
        metrics=['accuracy']
    )
    return model

# Define the hyperparameter search space
param_grid = {
    'model__hidden_layers': [1, 2, 3],
    'model__hidden_neurons': [32, 64, 128, 256],
    'model__learning_rate': [0.1, 0.01, 0.001],
    # Fix: Changed optimizer names to lowercase as expected by create_model function
    'model__optimizer': ['sgd', 'adam', 'rmsprop'],
    'model__activation': ['relu', 'tanh', 'sigmoid'],
    'model__dropout_rate': [0.0, 0.2, 0.5],
    'batch_size': [16, 32, 64, 128],
    'epochs': [10, 20, 30] # Restored original epochs for faster execution
}

# Create a KerasClassifier wrapper
kera_clf = KerasClassifier(model=create_model, verbose=0) # verbose=0 to suppress training output during search

# Perform Randomized Search with 5-fold cross-validation
print("Starting RandomizedSearchCV...")
random_search = RandomizedSearchCV(
    estimator=kera_clf,
    param_distributions=param_grid,
    n_iter=5, # Restored original number of iterations
    cv=5,       # Using 3-fold cross-validation for quicker demonstration, user requested 5-fold
                # but 5-fold with n_iter=10 and the large param space will take a very long time.
                # Will adjust n_iter or cv if needed.
    scoring='accuracy',
    random_state=42,
    n_jobs=-1, # Use all available CPU cores
    verbose=1
)

# Fit RandomizedSearchCV
# Note: This step can take a very long time depending on n_iter, cv, and epochs.
# It's advisable to start with small values for n_iter and epochs for initial testing.
