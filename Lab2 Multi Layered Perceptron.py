"""## Task 1: Dataset Exploration"""

import tensorflow as tf
import matplotlib.pyplot as plt
import numpy as np

# Load the Fashion-MNIST dataset
(x_train, y_train), (x_test, y_test) = tf.keras.datasets.fashion_mnist.load_data()

print(f"Training data shape: {x_train.shape}")
print(f"Training labels shape: {y_train.shape}")
print(f"Testing data shape: {x_test.shape}")
print(f"Testing labels shape: {y_test.shape}")

"""### Displaying Sample Images"""

# Define class names for Fashion-MNIST
class_names = [
    'T-shirt/top', 'Trouser', 'Pullover', 'Dress', 'Coat',
    'Sandal', 'Shirt', 'Sneaker', 'Bag', 'Ankle boot'
]

plt.figure(figsize=(10, 10))
for i in range(10):
    plt.subplot(5, 5, i + 1) # Adjust subplot grid to 5x5 if more images are needed, or 2x5 for 10 images
    plt.xticks([])
    plt.yticks([])
    plt.grid(False)
    plt.imshow(x_train[i], cmap=plt.cm.binary)
    plt.xlabel(class_names[y_train[i]])
plt.suptitle('Sample Fashion-MNIST Images', y=1.02, fontsize=16) # Add a suptitle for the entire figure
plt.tight_layout(rect=[0, 0, 1, 0.98]) # Adjust layout to prevent suptitle overlap
plt.show()

"""### Plotting Class Distribution"""

# Calculate class distribution
unique, counts = np.unique(y_train, return_counts=True)
plt.figure(figsize=(10, 6))
plt.bar(class_names, counts)
plt.xticks(rotation=45, ha='right')
plt.xlabel('Class')
plt.ylabel('Number of Images')
plt.title('Fashion-MNIST Training Data Class Distribution')
plt.tight_layout()
plt.show()

"""## Task 2: Data Preprocessing"""

print(f"Original training data shape: {x_train.shape}")
print(f"Original testing data shape: {x_test.shape}")

# 1. Flatten images
# Each image is 28x28 pixels. Flattening converts it to a 1D array of 784 pixels.
x_train_flat = x_train.reshape(-1, 28 * 28)
x_test_flat = x_test.reshape(-1, 28 * 28)

print(f"Flattened training data shape: {x_train_flat.shape}")
print(f"Flattened testing data shape: {x_test_flat.shape}")

# 2. Normalize pixel values to [0, 1]
x_train_norm = x_train_flat.astype('float32') / 255.0
x_test_norm = x_test_flat.astype('float32') / 255.0

print(f"Normalized training data shape: {x_train_norm.shape}")
print(f"Normalized testing data shape: {x_test_norm.shape}")

# 3. Convert labels into one-hot vectors
# There are 10 classes, so each label will be a 10-element vector with a 1 at the class index.
num_classes = 10
y_train_one_hot = tf.keras.utils.to_categorical(y_train, num_classes)
y_test_one_hot = tf.keras.utils.to_categorical(y_test, num_classes)

print(f"Original training labels shape: {y_train.shape}")
print(f"One-hot encoded training labels shape: {y_train_one_hot.shape}")
print(f"Original testing labels shape: {y_test.shape}")
print(f"One-hot encoded testing labels shape: {y_test_one_hot.shape}")

"""## Task 3: Model Construction"""

from tensorflow.keras import models, layers

# Define the MLP model
model = models.Sequential([
    layers.Input(shape=(784,)), # Input layer with 784 features
    layers.Dense(128, activation='relu'), # First hidden layer with 128 neurons and ReLU activation
    layers.Dense(64, activation='relu'),  # Second hidden layer with 64 neurons and ReLU activation
    layers.Dense(10, activation='softmax') # Output layer with 10 neurons (for 10 classes) and Softmax activation
])

# Display the model summary
model.summary()

"""## Task 4: Model Training"""

# Compile the model
model.compile(
    optimizer='adam',
    loss='categorical_crossentropy',
    metrics=['accuracy']
)

# Train the model
history = model.fit(
    x_train_norm,
    y_train_one_hot,
    epochs=20,
    batch_size=32,
    validation_split=0.2 # Use 20% of training data for validation
)

"""## Task 5: Model Evaluation"""

from sklearn.metrics import classification_report, confusion_matrix, accuracy_score, precision_score, recall_score, f1_score
import seaborn as sns

# Evaluate the model on the test data
loss, accuracy = model.evaluate(x_test_norm, y_test_one_hot, verbose=0)
print(f"Test Loss: {loss:.4f}")
print(f"Test Accuracy: {accuracy:.4f}")

# Make predictions on the test data
y_pred_probs = model.predict(x_test_norm)
y_pred = np.argmax(y_pred_probs, axis=1)

# Convert one-hot encoded y_test_one_hot back to class labels for evaluation metrics
y_true = np.argmax(y_test_one_hot, axis=1)

# Calculate Precision, Recall, F1-score
precision = precision_score(y_true, y_pred, average='weighted')
recall = recall_score(y_true, y_pred, average='weighted')
f1 = f1_score(y_true, y_pred, average='weighted')

print(f"Precision: {precision:.4f}")
print(f"Recall: {recall:.4f}")
print(f"F1-score: {f1:.4f}")

# Confusion Matrix
cm = confusion_matrix(y_true, y_pred)
plt.figure(figsize=(10, 8))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=class_names, yticklabels=class_names)
plt.xlabel('Predicted Label')
plt.ylabel('True Label')
plt.title('Confusion Matrix')
plt.show()

# Classification Report
print('\nClassification Report:')
print(classification_report(y_true, y_pred, target_names=class_names))

"""### Plotting Training and Validation Metrics"""

