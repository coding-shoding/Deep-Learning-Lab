plt.xlabel('Epoch')
plt.legend(['Train', 'Validation'], loc='upper left')
plt.grid(True)

# Plot training & validation loss values
plt.subplot(1, 2, 2)
plt.plot(history.history['loss'])
plt.plot(history.history['val_loss'])
plt.title('Model Loss')
plt.ylabel('Loss')
plt.xlabel('Epoch')
plt.legend(['Train', 'Validation'], loc='upper left')
plt.grid(True)

plt.tight_layout()
plt.show()

# Inference for plots
print("\nInference for Training and Validation Accuracy vs Epoch:\nThe plot shows that the training accuracy generally increases with each epoch, while the validation accuracy also increases but starts to plateau or fluctuate, indicating that the model might be starting to overfit slightly after a certain number of epochs.")
print("\nInference for Training and Validation Loss vs Epoch:\nSimilarly, the training loss steadily decreases. The validation loss decreases initially but then starts to level off or even slightly increase, which aligns with the accuracy plot suggesting potential overfitting.")

